#!/usr/bin/env python3
"""Generate launcher catalogs from options.json."""
import json
import sys
from pathlib import Path
root = Path(__file__).resolve().parent
options = json.loads((root / 'options.json').read_text())
help_text = 'Usage: otium [OPTIONS] [SCRIPT] [-- ARGUMENTS...]\n'
help_text += 'Options before -- belong to the launcher. Known inactive runtime options are ignored.\n'
for name, owner, kind, description in options:
    spelling = '--' + name
    if kind != 'flag':
        spelling += ('=' if owner != 'common' else ' ') + kind.upper()
    help_text += f'  {spelling:<28} {description} [{owner}]\n'
help_text += '  -h aliases --help; -L aliases --path.\n'
c = '/* Generated by shared/cli/generate.py. */\n'
c += 'static const struct { const char *name, *owner, *kind; } launcher_options[] = {\n'
for name, owner, kind, _ in options:
    c += '  {' + ', '.join(json.dumps(x) for x in (name, owner, kind)) + '},\n'
c += '};\nstatic const char launcher_help[] = ' + json.dumps(help_text) + ';\n'
def output(path, content):
    if '--check' in sys.argv:
        if path.read_text() != content:
            raise SystemExit(f'Stale generated file: {path}')
    else:
        path.write_text(content)

output(root / 'options.inc', c)
s = '(library (otium launcher-options)\n  (export launcher-options launcher-help)\n  (import (chezscheme))\n  (define launcher-options \'(\n'
for name, owner, kind, _ in options:
    s += '    (' + json.dumps(name) + ' ' + owner + ' ' + kind + ')\n'
s += '  ))\n  (define launcher-help ' + json.dumps(help_text) + '))\n'
output(root.parent.parent / 'chez/otium/launcher-options.sls', s)
