#!/usr/bin/env python3
"""Write a C file that embeds every file under the given directories.

Usage: embed-files.py OUTPUT DEPFILE ROOT DIRECTORY...

Each file is stored at its path relative to ROOT, with a leading slash. The
depfile lists the directories as well as the files, so adding or removing a
file regenerates the output.
"""

import os
import sys


def main():
    output, depfile, root = sys.argv[1:4]
    root = os.path.abspath(root)
    files = []
    directories = []
    for directory in sys.argv[4:]:
        for current, names, entries in os.walk(os.path.join(root, directory)):
            names.sort()
            directories.append(current)
            files.extend(os.path.join(current, entry) for entry in sorted(entries)
                         if not entry.startswith('.'))

    lines = ['/* Generated by tools/embed-files.py. */', '#include "files.h"', '']
    for index, path in enumerate(files):
        lines += [f'static const unsigned char file_{index}[] = {{',
                  f'#embed "{path}" suffix(,)', '0};']
    lines += ['', 'const embedded_file embedded_files[] = {']
    for index, path in enumerate(files):
        name = '/' + os.path.relpath(path, root)
        lines.append(f'    {{"{name}", file_{index}, sizeof file_{index} - 1}},')
    lines += ['};', f'const size_t embedded_file_count = {len(files)};', '']
    with open(output, 'w') as out:
        out.write('\n'.join(lines))
    with open(depfile, 'w') as out:
        out.write(output + ': ' + ' '.join(p.replace(' ', '\\ ') for p in directories + files) + '\n')


if __name__ == '__main__':
    main()
