#!/usr/bin/env python3
"""Combine the runtime into a single otium.c, in the style of SQLite.

Writes three files to OUTPUT_DIR:
  otium.h  the public header, unchanged
  otium.c  every internal header and runtime source, each included once
  main.c   the command-line launcher

Build with: cc otium.c main.c $(pkg-config --cflags --libs libffi) -lm -ldl -pthread

Local includes are expanded in place the first time they appear and dropped
after that. #line directives keep compiler messages pointing at the original
files. The runtime file list is read from the Makefile's RUNTIME variable.

Usage: tools/amalgamate.py OUTPUT_DIR
"""
from pathlib import Path
import re
import shutil
import sys

PROTOTYPE = Path(__file__).resolve().parents[1]
PUBLIC_HEADER = PROTOTYPE / 'include/otium.h'
INCLUDE = re.compile(r'\s*#\s*include\s+"([^"]+)"')


def runtime_sources():
    makefile = (PROTOTYPE / 'Makefile').read_text()
    match = re.search(r'^RUNTIME\s*=\s*((?:.*\\\n)*.*)$', makefile, re.M)
    return match.group(1).replace('\\\n', ' ').split()


def find(name, including):
    for directory in (including.parent, PROTOTYPE, PROTOTYPE / 'include'):
        path = directory / name
        if path.exists():
            return path.resolve()
    raise SystemExit(f'{including}: cannot find "{name}"')


def expand(path, seen, out):
    out.append(f'#line 1 "{path.relative_to(PROTOTYPE)}"\n')
    for number, line in enumerate(path.read_text().splitlines(keepends=True), 1):
        match = INCLUDE.match(line)
        if not match:
            out.append(line)
            continue
        target = find(match.group(1), path)
        if target == PUBLIC_HEADER.resolve():
            if target not in seen:
                seen.add(target)
                out.append('#include "otium.h"\n')
        elif target not in seen:
            seen.add(target)
            expand(target, seen, out)
        out.append(f'#line {number + 1} "{path.relative_to(PROTOTYPE)}"\n')


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    output = Path(sys.argv[1])
    output.mkdir(parents=True, exist_ok=True)
    seen, out = set(), ['/* Otium runtime amalgamation. Generated by tools/amalgamate.py. */\n']
    for source in runtime_sources():
        expand((PROTOTYPE / source).resolve(), seen, out)
    (output / 'otium.c').write_text(''.join(out))
    shutil.copyfile(PUBLIC_HEADER, output / 'otium.h')
    shutil.copyfile(PROTOTYPE / 'main.c', output / 'main.c')


if __name__ == '__main__':
    main()
