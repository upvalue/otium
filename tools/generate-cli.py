#!/usr/bin/env python3
"""Generate the launcher option table and help text from options.json."""
import json
import sys
from pathlib import Path
root = Path(__file__).resolve().parents[1]
options = json.loads((root / 'lib/catalog/options.json').read_text())
help_text = 'Usage: otium [OPTIONS] [SCRIPT] [-- ARGUMENTS...]\n'
help_text += 'Options before -- belong to the launcher.\n'
for name, kind, description in options:
    spelling = '--' + name
    if kind == 'optional-path':
        spelling += '[=PATH]'
    elif kind == 'milliseconds':
        spelling += '=MS'
    elif kind != 'flag':
        spelling += ('=' if kind == 'integer' else ' ') + kind.upper()
    help_text += f'  {spelling:<28} {description}\n'
help_text += '  -h aliases --help; -L aliases --path.\n'
c = '/* Generated by tools/generate-cli.py. */\n'
c += 'static const struct { const char *name, *kind; } launcher_options[] = {\n'
for name, kind, _ in options:
    c += '  {' + ', '.join(json.dumps(x) for x in (name, kind)) + '},\n'
c += '};\nstatic const char launcher_help[] = ' + json.dumps(help_text) + ';\n'
path = root / 'c/src/options.inc'
if '--check' in sys.argv:
    if path.read_text() != c:
        raise SystemExit(f'Stale generated file: {path}')
else:
    path.write_text(c)
